#!/usr/bin/env python3
"""Download the pinned 24px Sharp catalog using only Python's standard library.

Run from any directory: python3 apps/api/modules/swatchAndIcon/downloadMaterialSymbols.py
The existing catalog is replaced only after every SVG and the license validate.
"""

import concurrent.futures
import json
import math
import os
from pathlib import Path
import re
import sys
import tempfile
import time
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET


REVISION = "49d4db35df873165d6bd6ba09b063c7dafbac2f4"
REPOSITORY = "google/material-design-icons"
API_BASE = f"https://api.github.com/repos/{REPOSITORY}/git/trees/"
RAW_BASE = f"https://raw.githubusercontent.com/{REPOSITORY}/{REVISION}/"
OUTPUT_DIRECTORY = Path(__file__).resolve().parent
WORKERS = 12
SVG_NAMESPACE = "http://www.w3.org/2000/svg"


def download(url):
    """Retry temporary network failures; a permanent failure aborts generation."""
    request = urllib.request.Request(
        url, headers={"User-Agent": "qrk-material-symbols-downloader"}
    )
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=45) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code not in (429, 500, 502, 503, 504) or attempt == 3:
                raise
        except (urllib.error.URLError, TimeoutError):
            if attempt == 3:
                raise
        time.sleep(2**attempt)


def read_tree(reference):
    tree = json.loads(download(API_BASE + reference))
    if tree.get("truncated") or not isinstance(tree.get("tree"), list):
        raise ValueError(f"Incomplete Git tree: {reference}")
    return tree["tree"]


def child_tree(entries, name):
    matches = [entry for entry in entries if entry["path"] == name]
    if len(matches) != 1 or matches[0]["type"] != "tree":
        raise ValueError(f"Missing Git directory: {name}")
    return read_tree(matches[0]["sha"])


def icon_names():
    # 1. Enumerate directories from the pinned commit, without a truncated recursive tree.
    root = read_tree(REVISION)
    symbols = child_tree(root, "symbols")
    web = child_tree(symbols, "web")
    if not web or any(entry["type"] != "tree" for entry in web):
        raise ValueError("Unexpected entries in symbols/web")
    names = sorted(entry["path"] for entry in web)
    if len(set(names)) != len(names) or any(
        re.fullmatch(r"[a-z0-9_]+", name) is None for name in names
    ):
        raise ValueError("Invalid or duplicate icon names")
    return names


def download_icon(name):
    # 2. Fetch precisely one standard 24px Sharp SVG per icon and validate its geometry.
    path = f"symbols/web/{name}/materialsymbolssharp/{name}_24px.svg"
    svg = download(RAW_BASE + path).decode("utf-8").strip()
    root = ET.fromstring(svg)
    if root.tag != f"{{{SVG_NAMESPACE}}}svg":
        raise ValueError(f"Invalid SVG root: {path}")
    # Upstream includes 960-unit paths with different origins and 24-unit paths
    # without a viewBox, which use their declared 24px viewport directly.
    if root.get("viewBox") is not None:
        view_box = [float(value) for value in re.split(r"[\s,]+", root.get("viewBox").strip())]
        if (
            len(view_box) != 4
            or not all(math.isfinite(value) for value in view_box)
            or view_box[2] <= 0
            or view_box[3] <= 0
        ):
            raise ValueError(f"Unexpected SVG viewBox: {path}")
    if root.get("width") != "24" or root.get("height") != "24":
        raise ValueError(f"Unexpected SVG dimensions: {path}")
    if not any(
        element.tag == f"{{{SVG_NAMESPACE}}}path" and element.get("d")
        for element in root.iter()
    ):
        raise ValueError(f"SVG has no path data: {path}")
    return svg


def render_catalog(names, icons):
    # 3. Produce stable source: sorted slugs, human-readable names, and original SVGs.
    lines = [
        "// Generated by downloadMaterialSymbols.py; do not edit by hand.",
        f"// Source: https://github.com/{REPOSITORY}/tree/{REVISION}",
        f"// Revision: {REVISION}",
        "// Variant: symbols/web/<name>/materialsymbolssharp/<name>_24px.svg",
        f"// Imported icons: {len(names)}. License: Apache-2.0 (see LICENSE).",
        "",
        "export const materialSymbols: Record<string, { name: string; svg: string }> = {",
    ]
    for name in names:
        key = name if re.fullmatch(r"[a-z_][a-z0-9_]*", name) else json.dumps(name)
        svg = icons[name]
        svg_literal = json.dumps(svg)
        if svg.count('"') > svg.count("'"):
            svg_literal = "'" + (
                svg.replace("\\", "\\\\")
                .replace("'", "\\'")
                .replace("\n", "\\n")
                .replace("\r", "\\r")
                .replace("\t", "\\t")
            ) + "'"
        lines.extend(
            [
                f"  {key}: {{",
                f"    name: {json.dumps(name.replace('_', ' '))},",
                f"    svg: {svg_literal},",
                "  },",
            ]
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    names = icon_names()
    print(f"Downloading {len(names)} Sharp 24px icons at {REVISION}", flush=True)
    icons = {}
    failures = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=WORKERS) as executor:
        futures = {executor.submit(download_icon, name): name for name in names}
        for completed, future in enumerate(concurrent.futures.as_completed(futures), start=1):
            name = futures[future]
            try:
                icons[name] = future.result()
            except Exception as error:
                failures.append(f"{name}: {error}")
            if completed % 500 == 0 or completed == len(names):
                print(f"Validated {len(icons)}/{len(names)} SVGs ({completed} fetched)", flush=True)
    if failures:
        raise RuntimeError(
            f"{len(failures)} SVGs failed download or validation: " + "; ".join(sorted(failures)[:10])
        )
    if len(icons) != len(names) or set(icons) != set(names):
        raise ValueError("Incomplete SVG catalog")

    license_text = download(RAW_BASE + "LICENSE").decode("utf-8")
    if "Apache License" not in license_text or "Version 2.0" not in license_text:
        raise ValueError("Missing upstream Apache 2.0 license")
    outputs = {"LICENSE": license_text, "materialSymbols.ts": render_catalog(names, icons)}

    # 4. Stage all output only after a complete download, then replace the catalog atomically.
    staged = []
    try:
        for filename, contents in outputs.items():
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", newline="\n", dir=OUTPUT_DIRECTORY, delete=False
            ) as temporary:
                temporary.write(contents)
                staged.append((Path(temporary.name), OUTPUT_DIRECTORY / filename))
        for temporary, destination in staged:
            os.replace(temporary, destination)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)
    print(f"Wrote materialSymbols.ts and LICENSE with {len(icons)} icons", flush=True)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Catalog generation failed: {error}", file=sys.stderr)
        sys.exit(1)
